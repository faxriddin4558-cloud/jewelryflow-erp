#!/usr/bin/env python3
"""Generates supabase/release/function_body_parity_<NNN>_full_readonly.sql: CR-tolerant function-body parity of ALL
functions in schema public (extension members excluded) with the repository 001..NNN, from a FRESH local PostgreSQL 17
that has the migrations applied from LF files (docs/releases/staging-075/harness/stack-db.sh).
Statuses: identical | crlf_only (differs ONLY by carriage returns from a Windows checkout - same code) |
DIFFERENT (real code difference) | MISSING (in the repository, not on the target) | EXTRA (on the target, not in the repository).
Usage: python3 gen-function-parity-full.py 080 [port] [database]"""
import os, subprocess, sys
v = sys.argv[1]; port = sys.argv[2] if len(sys.argv) > 2 else '55437'; db = sys.argv[3] if len(sys.argv) > 3 else 'postgres'
here = os.path.dirname(os.path.abspath(__file__)); repo = os.path.abspath(os.path.join(here, '..', '..', '..'))
env = {**os.environ, 'PATH': '/opt/goldia-audit/pg17root/wrap:' + os.environ['PATH']}
q = lambda sql: subprocess.run(['psql', '-h', '127.0.0.1', '-p', port, '-U', 'postgres', '-d', db, '-X', '-A', '-t', '-F', '|', '-c', sql], capture_output=True, text=True, env=env, check=True).stdout
latest = q("select max(version) from supabase_migrations.schema_migrations").strip()
assert latest == f'20260101000{v}', f'local copy is at {latest}, not {v}'
cr = q("select count(*) from pg_proc p where p.pronamespace = 'public'::regnamespace and position(chr(13) in p.prosrc) > 0").strip()
assert cr == '0', f'the reference copy contains CR characters in {cr} function bodies - apply the migrations from LF files'
rows = [l.split('|') for l in q("""select p.oid::regprocedure::text, md5(p.prosrc) from pg_proc p where p.pronamespace = 'public'::regnamespace
  and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e') order by 1""").strip().splitlines()]
vals = ',\n'.join("  ('{}', '{}')".format(s.replace("'", "''"), h) for s, h in rows)
sql = f"""-- READ ONLY. CR-tolerant function-body parity of ALL functions in schema public with the repository (001..{v}).
-- Generated by docs/releases/production-075/gen-function-parity-full.py from a fresh PostgreSQL 17 copy (LF files).
-- status: identical | crlf_only (differs ONLY by carriage returns, e.g. migrations run from a Windows checkout: same code,
-- no behavioural effect) | DIFFERENT (real code difference -> review) | MISSING (repository function absent) | EXTRA
-- (function on the target that the repository does not have). RESULT|function_parity_{v}|OK when DIFFERENT, MISSING
-- and EXTRA are all 0.
-- Run: psql "<connection>" -X -v ON_ERROR_STOP=1 -f <this file>   or   run-readonly-checks.ps1 -ExtraCheckFile <this file>
begin transaction read only;
with expected(sig, h) as (values
{vals}
), actual as (
  select p.oid::regprocedure::text as sig, md5(p.prosrc) as h_raw, md5(replace(p.prosrc, chr(13), '')) as h_lf,
         (length(p.prosrc) - length(replace(p.prosrc, chr(13), ''))) as cr_count
    from pg_proc p
   where p.pronamespace = 'public'::regnamespace
     and not exists (select 1 from pg_depend d where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e')
), judged as (
  select coalesce(e.sig, a.sig) as sig,
         case when a.sig is null then 'MISSING'
              when e.sig is null then 'EXTRA'
              when a.h_raw = e.h then 'identical'
              when a.h_lf = e.h then 'crlf_only'
              else 'DIFFERENT' end as status,
         a.cr_count
    from expected e full join actual a on a.sig = e.sig
)
select status || '|' || count(*) from judged group by status
union all
select 'DETAIL ' || status || ' ' || sig || '|' || coalesce(cr_count, 0) from judged where status in ('DIFFERENT', 'MISSING', 'EXTRA', 'crlf_only')
union all
select 'RESULT|function_parity_{v}|' || case when count(*) filter (where status in ('DIFFERENT', 'MISSING', 'EXTRA')) = 0 then 'OK' else 'REVIEW' end
       || '|identical=' || count(*) filter (where status = 'identical') || ' crlf_only=' || count(*) filter (where status = 'crlf_only')
       || ' different=' || count(*) filter (where status = 'DIFFERENT') || ' missing=' || count(*) filter (where status = 'MISSING')
       || ' extra=' || count(*) filter (where status = 'EXTRA') from judged
order by 1;
rollback;
"""
open(os.path.join(repo, f'supabase/release/function_body_parity_{v}_full_readonly.sql'), 'w').write(sql)
print(f'written supabase/release/function_body_parity_{v}_full_readonly.sql ({len(rows)} functions)')
