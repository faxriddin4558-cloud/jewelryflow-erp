#!/usr/bin/env python3
"""Generates emergency rollback files for production: rollback NNN + removal of its history row, in ONE transaction,
guarded so that only the newest recorded migration can be rolled back (076, then 075, 074, 073)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
out_dir = os.path.join(HERE, 'emergency')
os.makedirs(out_dir, exist_ok=True)
for v in ['076', '075', '074', '073']:
    ver = '20260101000' + v
    body = open(os.path.join(REPO, f'supabase/rollback/{ver}_rollback.sql')).read()
    sql = f"""-- EMERGENCY ROLLBACK {v} (production). Generated by docs/releases/production-075/gen-emergency-rollback.py.
-- Run ONLY with the owner's approval, in ONE transaction:
--   psql "<production connection>" -X -v ON_ERROR_STOP=1 --single-transaction -f docs/releases/production-075/emergency/rollback_{v}_with_history.sql
-- Order: 076 first, then 075, 074, 073. Keeps every business row; removes the {v} history row so the migration history
-- matches the schema again (the plain supabase/rollback file does not touch supabase_migrations).
set lock_timeout = '10s';
set statement_timeout = '5min';
do $guard$
begin
  if to_regprocedure('public.deployment_environment()') is not null then
    raise exception 'STOP: JewelryFlow SaaS demo database, not Goldia';
  end if;
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '{ver}') then
    raise exception 'STOP: migration {v} is not recorded — nothing to roll back';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations where version > '{ver}') then
    raise exception 'STOP: a newer migration is recorded — roll that back first';
  end if;
end $guard$;

-- ===== supabase/rollback/{ver}_rollback.sql =====
{body}
;
reset all;
delete from supabase_migrations.schema_migrations where version = '{ver}';
"""
    open(os.path.join(out_dir, f'rollback_{v}_with_history.sql'), 'w').write(sql)
    print('written', f'emergency/rollback_{v}_with_history.sql')
